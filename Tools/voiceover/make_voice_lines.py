"""Voice lines for Story Mode conversations.

Reads Assets/Resources/Story/story_script.json and, for every line a character speaks (not your replies):

  python Tools/voiceover/make_voice_lines.py sheet
      Writes the recording script for voice actors:
        Documentation/voice-script.csv  (one row per file to record)
        Documentation/voice-script.md   (the same, grouped by character, easy to read aloud)

  python Tools/voiceover/make_voice_lines.py scratch [--only CONVERSATION_ID ...]
      Makes placeholder WAVs with the Windows voices (Microsoft Zira for women, David for men) into
      Assets/Resources/Story/VO/, so the game speaks right away. These are SCRATCH ONLY: they mispronounce
      Kinyarwanda and must be replaced by real recordings before release (asset register VO-001).

  python Tools/voiceover/make_voice_lines.py check
      Lists which lines have a recording and which are missing.

File names (the game finds them by name, nothing else to set up):
  <conversation>_<node>.wav        a named character (Maman Fils, Jean-Paul ...)
  <conversation>_<node>_f.wav      a line shared by many staff, spoken by a woman
  <conversation>_<node>_m.wav      the same line spoken by a man
Real recordings: export mono WAV (44.1 or 48 kHz), drop them into Assets/Resources/Story/VO/ with these
names; they replace the scratch files. ElevenLabs downloads: Tools/voiceover/import_elevenlabs.py.
"""
import csv
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCRIPT = os.path.join(ROOT, "Assets", "Resources", "Story", "story_script.json")
VO_DIR = os.path.join(ROOT, "Assets", "Resources", "Story", "VO")
DOC_DIR = os.path.join(ROOT, "Documentation")

# Who speaks each conversation's lines (from StoryModeBuilder / CityServicesBuilder).
# "fm" = shared by staff of both sexes: record a woman's and a man's take.
VOICES = {
    "maman_fils": ("Maman Fils", "f"),
    "aline": ("Aline", "f"),
    "officer": ("Officer Mukamana", "f"),
    "waitress": ("Waitress", "f"),
    "jean_paul": ("Jean-Paul", "m"),
    "gakuba": ("Mzee Gakuba", "m"),
    "other_driver": ("The other driver (accident)", "m"),
    "staff": ("Staff (cafes, shops, clinics...)", "fm"),
    "police": ("Police officer on patrol", "fm"),
}
TTS = {"f": "Microsoft Zira Desktop", "m": "Microsoft David Desktop"}

# Kinyarwanda words in the script, flagged so the actor and a native speaker check them.
KINYARWANDA = ["muraho", "mwaramutse", "mwiriwe", "murakoze", "murakaza", "amakuru", "ni meza", "icyayi",
               "mzee", "yego", "oya", "cyane", "neza", "mbabarira", "turabonana", "ndashaka", "amafaranga"]


def lines():
    data = json.load(open(SCRIPT, encoding="utf-8"))
    for conv in data["conversations"]:
        who, sexes = VOICES.get(conv.get("npc"), (conv.get("npc") or "?", "fm"))
        for node in conv["nodes"]:
            if node.get("speaker") == "you" or not node.get("text"):
                continue
            text = node["text"]
            spoken = text.replace("{place}", "here").replace("{name}", "")
            notes = []
            if "{place}" in text or "{name}" in text:
                notes.append("names the business: say it so it works anywhere ('here')")
            kin = [w for w in KINYARWANDA if w in text.lower()]
            if kin:
                notes.append("Kinyarwanda: " + ", ".join(kin) + " (native speaker to check)")
            for sex in (sexes if sexes != "fm" else "fm"):
                suffix = "" if sexes != "fm" else "_" + sex
                yield {
                    "file": f"{conv['id']}_{node['id']}{suffix}.wav",
                    "conversation": conv["id"],
                    "node": node["id"],
                    "character": who,
                    "voice": "woman" if sex == "f" else "man",
                    "sex": sex,
                    "line": text,
                    "spoken": spoken,
                    "notes": "; ".join(notes),
                }


def sheet():
    rows = list(lines())
    os.makedirs(DOC_DIR, exist_ok=True)
    cols = ["file", "character", "voice", "line", "notes", "conversation", "node"]
    with open(os.path.join(DOC_DIR, "voice-script.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(DOC_DIR, "voice-script.md"), "w", encoding="utf-8") as f:
        f.write("# Story Mode voice script\n\n")
        f.write("Generated by `Tools/voiceover/make_voice_lines.py sheet` from `story_script.json`. "
                "Record each line as a separate mono WAV named exactly as shown, then copy the files into "
                "`Assets/Resources/Story/VO/`.\n\n")
        f.write("- Leave about half a second of silence before and after each line.\n")
        f.write("- A native speaker should check every line marked Kinyarwanda.\n")
        f.write("- Shared staff lines need a woman's take (`_f`) and a man's take (`_m`).\n\n")
        by = {}
        for r in rows:
            by.setdefault((r["character"], r["voice"]), []).append(r)
        for (who, voice), rs in by.items():
            f.write(f"## {who} ({voice}, {len(rs)} lines)\n\n")
            last = None
            for r in rs:
                if r["conversation"] != last:
                    f.write(f"**{r['conversation']}**\n\n")
                    last = r["conversation"]
                note = f"  \n  _{r['notes']}_" if r["notes"] else ""
                f.write(f"- `{r['file']}`: {r['line']}{note}\n")
            f.write("\n")
    takes = {}
    for r in rows:
        takes[r["voice"]] = takes.get(r["voice"], 0) + 1
    print(f"{len(rows)} files to record ({takes}) -> Documentation/voice-script.csv and .md")


def recorded():
    """Real recordings (Tools/voiceover/recorded.json, written by import_elevenlabs.py): never overwritten."""
    path = os.path.join(os.path.dirname(__file__), "recorded.json")
    return set(json.load(open(path, encoding="utf-8"))) if os.path.exists(path) else set()


def base_file(r):
    return f"{r['conversation']}_{r['node']}.wav"


def scratch(only):
    real = recorded()
    rows = [r for r in lines() if (not only or r["conversation"] in only) and base_file(r) not in real]
    os.makedirs(VO_DIR, exist_ok=True)
    # One PowerShell run for all lines (System.Speech, offline, built into Windows).
    ps = ["Add-Type -AssemblyName System.Speech",
          "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer",
          "$s.Rate = -1"]
    for r in rows:
        out = os.path.join(VO_DIR, r["file"]).replace("'", "''")
        text = r["spoken"].replace("'", "''")
        ps.append(f"$s.SelectVoice('{TTS[r['sex']]}'); $s.SetOutputToWaveFile('{out}'); $s.Speak('{text}')")
    ps.append("$s.SetOutputToNull(); $s.Dispose()")
    with tempfile.NamedTemporaryFile("w", suffix=".ps1", delete=False, encoding="utf-8-sig") as f:
        f.write("\n".join(ps))
        path = f.name
    try:
        subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", path], check=True)
    finally:
        os.remove(path)
    print(f"{len(rows)} scratch lines -> Assets/Resources/Story/VO/ (placeholders; replace with real recordings)")


def check():
    rows = list(lines())
    have = set(os.listdir(VO_DIR)) if os.path.isdir(VO_DIR) else set()
    real = recorded()
    done = [r for r in rows if base_file(r) in real]
    missing = [r["file"] for r in rows if r["file"] not in have and base_file(r) not in have]
    print(f"{len(done)}/{len(rows)} lines recorded; {len(rows) - len(done) - len(missing)} use scratch voices; {len(missing)} silent")
    for r in rows:
        if base_file(r) not in real:
            print("  scratch" if r["file"] not in missing else "  missing", r["file"])


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "sheet"
    if cmd == "sheet":
        sheet()
    elif cmd == "scratch":
        only = sys.argv[sys.argv.index("--only") + 1:] if "--only" in sys.argv else []
        scratch(only)
    elif cmd == "check":
        check()
    else:
        print(__doc__)
